#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проверка paper.tex на соответствие ГОСТ Р 7.0.7-2021.

ГОСТ Р 7.0.7-2021 «СИБИД. Статьи в журналах и сборниках. Издательское
оформление» — утв. приказом Росстандарта от 18.08.2021 № 728-ст, введён в
действие 01.10.2021 взамен ГОСТ Р 7.0.7-2009. Статус на 27.08.2026: действует.

Смежные действующие стандарты, на которые он ссылается:
  ГОСТ Р 7.0.5-2008  — библиографическая ссылка (действует, замен нет);
  ГОСТ Р 7.0.99-2018 — реферат и аннотация (взамен ГОСТ 7.9-95, утратившего силу);
  ГОСТ Р 7.0.100-2018 — библиографическое описание;
  ГОСТ 7.79 — транслитерация кириллицы латиницей.

Проверяются только те пункты, которые относятся к авторской части статьи.
Элементы, заполняемые редакцией (сведения об издании, рубрика, DOI, знак охраны
авторского права, даты поступления/одобрения/принятия), не проверяются —
они перечислены отдельно как зона ответственности журнала.

Код возврата 1, если есть нарушения.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEX = (HERE / "paper.tex").read_text(encoding="utf-8")

RESULTS = []


def check(clause, what, ok, detail=""):
    RESULTS.append((clause, what, bool(ok), detail))


# ── п. 4.4: тип статьи в начале отдельной строкой слева ─────────────────────
check("4.4", "тип статьи указан в начале",
      re.search(r"\\noindent\s+Научная статья", TEX) is not None)

# ── п. 4.5: индекс УДК в начале отдельной строкой слева ─────────────────────
m = re.search(r"\\noindent\s+УДК\s+([0-9.:()\[\]/+-]+)", TEX)
check("4.5", "индекс УДК приведён", m is not None,
      m.group(1) if m else "")

# ── п. 4.7: в конце заглавия статьи точку не ставят ─────────────────────────
mt = re.search(r"\\title\{(.*?)\}\s*\n\\author", TEX, re.S)
title = re.sub(r"\\\\|\n", " ", mt.group(1)).strip() if mt else ""
check("4.7", "в конце заглавия нет точки", not title.endswith("."))

# ── п. 4.10: объём аннотации не превышает 250 слов ──────────────────────────
def abstract_words(block):
    txt = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?(\{[^{}]*\})?", " ", block)
    txt = re.sub(r"[${}\\~]", " ", txt)
    return len(txt.split())


ab = re.findall(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", TEX, re.S)
for i, a in enumerate(ab):
    # благодарности и финансирование в объём аннотации не входят
    core = re.split(r"\\textbf\{(?:Ключевые слова|Keywords)", a)[0]
    n = abstract_words(core)
    check("4.10", "объём аннотации %s ≤ 250 слов" % ("(рус.)" if i == 0 else "(англ.)"),
          n <= 250, "%d слов" % n)

check("4.10", "перед аннотацией приведено слово «Аннотация»/«Abstract»",
      "\\begin{abstract}" in TEX and "Abstract." in TEX)

# ── п. 4.11: 3..15 ключевых слов, после них точку не ставят ─────────────────
for lang, pat in (("рус.", r"\\textbf\{Ключевые слова:\}(.*?)\n\n"),
                  ("англ.", r"\\textbf\{Keywords:\}(.*?)\n\n")):
    mk = re.search(pat, TEX, re.S)
    if not mk:
        check("4.11", "ключевые слова (%s) присутствуют" % lang, False)
        continue
    raw = mk.group(1).replace("\n", " ").strip()
    n = len([x for x in raw.rstrip(".").split(",") if x.strip()])
    check("4.11", "число ключевых слов (%s) в диапазоне 3..15" % lang,
          3 <= n <= 15, "%d" % n)
    check("4.11", "после ключевых слов (%s) точка не стоит" % lang,
          not raw.endswith("."))

# ── п. 4.12: благодарности и финансирование ПОСЛЕ ключевых слов ─────────────
for lang, kw, ack in (("рус.", "Ключевые слова:", "Благодарности:"),
                      ("англ.", "Keywords:", "Acknowledgments:")):
    ik, ia = TEX.find(kw), TEX.find(ack)
    check("4.12", "благодарности (%s) идут после ключевых слов" % lang,
          ik != -1 and ia != -1 and ia > ik)
for lang, fund in (("рус.", "Финансирование:"), ("англ.", "Funding:")):
    check("4.12", "сведения о финансировании (%s) приведены" % lang, fund in TEX)

# ── п. 4.14: заголовок перечня — «Список источников» ────────────────────────
check("4.14", "перечень озаглавлен «Список источников»",
      r"\renewcommand{\refname}{Список источников}" in TEX)
check("4.14", "не используются слова «Библиографический список»/«Библиография»",
      "Библиографический список" not in TEX and "\\section*{Библиография}" not in TEX)

# ── п. 4.14.1: только процитированные ресурсы ──────────────────────────────
body = TEX[TEX.index("\\section{Введение}"):TEX.index("\\begin{thebibliography}")]
cited, seen = [], set()
for mm in re.finditer(r"\\cite\{([^}]*)\}", body):
    for k in mm.group(1).split(","):
        k = k.strip()
        if k and k not in seen:
            seen.add(k)
            cited.append(k)
bib = re.findall(r"\\bibitem\{([^}]*)\}", TEX)
check("4.14.1", "в перечне только процитированные источники",
      set(bib) == set(cited),
      "не цитируются: %s" % sorted(set(bib) - set(cited)) if set(bib) - set(cited) else "")

# ── п. 4.14.3: нумерация в порядке цитирования ─────────────────────────────
check("4.14.3", "записи расположены в порядке цитирования", bib == cited,
      "требуется: %s" % cited if bib != cited else "")

# ── п. 4.14.4: дополнительный перечень на латинице с той же нумерацией ─────
mref = re.search(r"\\section\*\{References\}\s*\\begin\{enumerate\}(.*?)\\end\{enumerate\}",
                 TEX, re.S)
n_ref = len(re.findall(r"\\item(?![a-zA-Z])", mref.group(1))) if mref else 0
check("4.14.4", "приведён перечень на латинице (References)", mref is not None)
check("4.14.4", "нумерация References совпадает с основным перечнем",
      n_ref == len(bib), "%d против %d" % (n_ref, len(bib)))

# ── п. 4.1.6: англоязычный блок до основного текста ────────────────────────
for what, needle in (("заглавие", "The observation scheme in the statistics"),
                     ("имя автора", "Timofei"),
                     ("аффилиация", "Independent researcher, Irkutsk, Russia"),
                     ("аннотация", "Abstract."),
                     ("ключевые слова", "Keywords:")):
    check("4.1.6", "англоязычный блок: %s" % what, needle in TEX)

# ── п. 4.9: формат основных сведений об авторе ─────────────────────────────
check("4.9", "раздел «Информация об авторе» присутствует",
      "\\section*{Информация об авторе}" in TEX)
check("4.9", "ORCID приведён в форме URL",
      "https://orcid.org/0009-0006-0510-5225" in TEX)
check("4.9", "электронный адрес приведён без слова «e-mail»",
      not re.search(r"E-mail:\s*\\texttt", TEX))

# ── п. 4.20.3: конфликт интересов в конце, после сведений об авторе ────────
i_auth = TEX.rfind("Information about the author")
i_conf = TEX.find("Автор заявляет об отсутствии конфликта интересов")
check("4.20.3", "конфликт интересов указан после «Информации об авторе»",
      i_conf > i_auth > 0)
check("4.20.3", "конфликт интересов продублирован на английском",
      "The author declares no conflicts of interests" in TEX)

# ── п. 4.1.5: подписи к иллюстративному материалу — на языке статьи и,
#    «как правило», на английском. Формально рекомендация; проверяем как
#    выполненную, чтобы она не разошлась с текстом при правках. ───────────────
n_cap = len(re.findall(r"\\caption\{", TEX))
n_en = len(re.findall(r"\\encaptab\{|\\encapfig\{", TEX))
check("4.1.5", "все подписи продублированы на английском", n_cap == n_en and n_cap > 0,
      "%d из %d" % (n_en, n_cap))

# ── элементы, заполняемые редакцией (не проверяем, только перечисляем) ─────
EDITORIAL = [
    ("4.2", "сведения об издании (заглавие, год, том, номер, страницы, ISSN)"),
    ("4.3", "название рубрики или раздела издания"),
    ("4.6", "DOI статьи"),
    ("4.13", "знак охраны авторского права"),
    ("4.19", "даты поступления, одобрения и принятия статьи"),
    ("4.20.1", "библиографическая запись «Для цитирования:» / “For citation:”"),
]

# ── рекомендации (не требования) ──────────────────────────────────────────
ADVISORY = [
    ("4.1.5", "основной текст может быть структурирован разделами "
              "«Материалы и методы», «Результаты», «Обсуждение»; "
              "п. 4.1.5 прямо допускает и тематическую рубрикацию, "
              "применённую здесь"),
    ("4.15", "пристатейный библиографический список (записи по теме, на "
             "которые нет ссылок) — необязателен, не приводится"),
]


def main():
    bad = 0
    print("Проверка по ГОСТ Р 7.0.7-2021 (действует с 01.10.2021; "
          "статус на 27.08.2026 — действующий)")
    print("=" * 78)
    print("%-9s %-52s %s" % ("пункт", "требование", "статус"))
    print("-" * 78)
    for clause, what, ok, detail in RESULTS:
        mark = "ОК" if ok else "НАРУШЕНО"
        line = "%-9s %-52s %s" % (clause, what[:52], mark)
        if detail:
            line += "  [%s]" % detail
        print(line)
        if not ok:
            bad += 1
    print("-" * 78)
    print("нарушений: %d из %d" % (bad, len(RESULTS)))
    print()
    print("Заполняет редакция издания (авторская часть не затрагивается):")
    for c, w in EDITORIAL:
        print("  п. %-8s %s" % (c, w))
    print()
    print("Рекомендации ГОСТ («как правило»), не требования:")
    for c, w in ADVISORY:
        print("  п. %-8s %s" % (c, w))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Устойчивость выводов статьи к выбору зерна генератора.

Числа Монте-Карло в статье получены при одном фиксированном зерне. Это делает их
воспроизводимыми, но НЕ доказывает, что вывод не зависит от конкретной
реализации. Здесь анализ прогоняется при нескольких зёрнах, и для каждой
несущей вывод величины проверяется, что она остаётся внутри объявленного
коридора.

Коридоры заданы содержательно: не «совпало до знака», а «вывод тот же».

Запуск:  python3 check_stability.py [число_зёрен]
Код возврата 1, если хоть одна величина вышла за коридор.
"""
import re
import subprocess
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SEEDS = [20260827, 1, 42, 777, 123456]

# имя -> (регулярное выражение с одной группой, нижняя граница, верхняя,
#         что именно проверяется)
PROBES = {
    "ошибка I рода при схеме B (заявлено 0,162)":
        (r"B, сдвиг 0\.0\s+([\d.]+)", 0.14, 0.19,
         "критерий должен отвергать втрое чаще номинала"),
    "E[(M-B)/S] при наблюдённом фронте (истинное 1,7811)":
        (r"E\[#событий\] = наблюдённое\s+([\d.]+)", 1.770, 1.793,
         "оценка схемы B несмещена"),
    "E[(M-1)/S] при наблюдённом фронте":
        (r"E\[#событий\] = наблюдённое\s+[\d.]+\s+[+-][\d.]+%\s+([\d.]+)",
         1.87, 1.94, "оценка схемы A смещена вверх примерно на 7%"),
    "нижний конец ДИ схемы B (заявлено 1,613)":
        (r"kappa\^_B = [\d.]+, 95% ДИ = \[([\d.]+); ", 1.55, 1.68,
         "интервал накрывает e^gamma"),
    "верхний конец ДИ схемы B (заявлено 2,130)":
        (r"kappa\^_B = [\d.]+, 95% ДИ = \[[\d.]+; ([\d.]+)\]", 2.05, 2.22,
         "интервал накрывает e^gamma"),
    "p-значение схемы B (заявлено 0,639)":
        (r"kappa\^_B = [\d.]+, 95% ДИ = \[[\d.]+; [\d.]+\], p = ([\d.]+)",
         0.50, 0.80, "согласие с ЛПВ не отвергается"),
    "cv для мощности 80% (заявлено 0,34)":
        (r"мощность 80% достигается при cv ~ ([\d.]+)", 0.30, 0.40,
         "критерий однородности слеп к разбросу порядка трети"),
    "p свободного члена, §7 (заявлено 0,562)":
        (r"5-95% \[[-\d.]+; [\d.]+\], p = ([\d.]+)", 0.40, 0.70,
         "вторичный член незначим"),
    "p для max|r|, §7 (заявлено 0,539)":
        (r"max\|r\| наблюдённое [\d.]+, медиана симуляций [\d.]+, p = ([\d.]+)",
         0.35, 0.70, "недодисперсии нет"),
    "p серединной экскурсии, §7 (заявлено 0,280)":
        (r"средняя экскурсия.*?p = ([\d.]+)", 0.15, 0.45,
         "серединного дефицита нет"),
    "смещение kappa* при схеме B, §4.3 (заявлено +7,51%)":
        (r"взвешенное среднее kappa\* при схеме B: смещение \+([\d.]+)%",
         6.5, 8.5, "объединение с обратно-дисперсионными весами не спасает"),
}

# детерминированные величины: от зерна не зависят вовсе, должны совпасть точно
EXACT = {
    "M": r"M = (\d+), S =",
    "S": r"M = \d+, S = ([\d.]+)",
    "(M-1)/S": r"схема A: kappa~ = \(M-1\)/S = ([\d.]+)",
    "(M-B)/S": r"схема B: kappa\^ = \(M-B\)/S = ([\d.]+)",
    "Lambda": r"Lambda = ([\d.]+) при 14",
    "ln L модели A": r"^\s+A\s+\d+\s+(-[\d.]+)",
}


def run(seed):
    out = HERE / ("results_seed%d.txt" % seed)
    if not out.exists():
        subprocess.run([sys.executable, str(HERE / "analysis.py"),
                        "--seed", str(seed)], cwd=HERE,
                       capture_output=True, check=True)
    return out.read_text(encoding="utf-8")


def grab(text, pat):
    m = re.search(pat, text, re.M | re.S)
    return float(m.group(1)) if m else None


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else len(SEEDS)
    seeds = SEEDS[:n]
    print("Устойчивость к зерну генератора: %d прогонов %s" % (len(seeds), seeds))
    print("=" * 92)

    texts = {}
    for s in seeds:
        print("  прогон при зерне %d ..." % s, flush=True)
        texts[s] = run(s)

    bad = 0

    print()
    print("Детерминированные величины (не зависят от зерна) — должны совпасть точно:")
    print("-" * 92)
    for name, pat in EXACT.items():
        vals = [grab(texts[s], pat) for s in seeds]
        ok = all(v is not None for v in vals) and len(set(vals)) == 1
        print("  %-24s %-18s %s" % (name, vals[0], "ОК" if ok else "РАСХОЖДЕНИЕ %s" % vals))
        if not ok:
            bad += 1

    print()
    print("Величины Монте-Карло — должны остаться внутри содержательного коридора:")
    print("-" * 92)
    print("  %-46s %8s %8s %8s %s" % ("величина", "мин", "макс", "разброс", "коридор"))
    for name, (pat, lo, hi, why) in PROBES.items():
        vals = [grab(texts[s], pat) for s in seeds]
        if any(v is None for v in vals):
            print("  %-46s  НЕ ИЗВЛЕЧЕНО" % name[:46])
            bad += 1
            continue
        mn, mx = min(vals), max(vals)
        ok = lo <= mn and mx <= hi
        print("  %-46s %8.4f %8.4f %8.4f  [%.3f; %.3f] %s"
              % (name[:46], mn, mx, mx - mn, lo, hi, "ОК" if ok else "ВЫШЛА"))
        if not ok:
            bad += 1
            print("      нарушен вывод: %s" % why)

    print("-" * 92)
    print("величин вне коридора: %d" % bad)
    if bad == 0:
        print("Вывод: ни одно утверждение работы не зависит от выбора зерна.")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())

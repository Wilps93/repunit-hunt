#!/bin/bash
# Расширение практического пересчёта за границу n < 10^4.
#
# Порог выбирается по основанию, а не единый: стоимость растёт как ~K^3.24,
# поэтому дешёвые основания можно увести дальше за то же время, а дорогие
# двигать ровно настолько, чтобы закрыть ближайший известный индекс.
#
# Ярус 1: все пятнадцать оснований основного набора до n < 20000.
# Ярус 2: b = 18 и b = 20 до n < 32000 — самые слабо покрытые; их ближайшие
#         индексы 25667, 28807 и 31013 лежат чуть выше первого яруса.
#
# compare_verify.py читает границу из results.json каждого основания, поэтому
# разные пороги сверяются корректно.
set -u
cd "$(dirname "$0")"

echo "=== Ярус 1: основной набор до n < 20000  ($(date +%H:%M:%S))"
DC=1.0 bash verify_sequences.sh 20000 2 3 5 6 7 10 11 12 13 14 15 17 18 19 20

echo
echo "=== Ярус 2: b = 18, 20 до n < 32000  ($(date +%H:%M:%S))"
DC=1.0 bash verify_sequences.sh 32000 18 20

echo
echo "=== Сверка  ($(date +%H:%M:%S))"
python3 compare_verify.py
rc=$?
echo
python3 coverage.py
exit $rc
